namespace graphic_editor.Interfaces;

/// <summary>
/// Базовый интерфейс для всех действий, поддерживаемых системой истории (Undo/Redo).
/// Определяет контракт для отмены и повтора операций в редакторе.
/// </summary>
public interface IHistoryAction
{
    /// <summary>
    /// Получает человеко-читаемое описание действия для отображения в UI.
    /// </summary>
    string Description { get; }
    
    /// <summary>
    /// Отменяет выполненное действие, возвращая состояние редактора к предыдущему.
    /// Должен быть обратим к методу Redo().
    /// </summary>
    void Undo();
    
    /// <summary>
    /// Повторяет ранее отменённое действие, применяя изменения к текущему состоянию.
    /// Должен быть обратим к методу Undo().
    /// </summary>
    void Redo();
}